/**
  * @brief  Board bring-up, then micro T-Kernel (the application starts in
  *         usermain)
  * @retval int
  */
int main(void)
{
  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* Enable the CPU Cache */
  SCB_EnableICache();
  SCB_EnableDCache();

  /* MCU Configuration--------------------------------------------------------*/
  HAL_Init();

  /* USER CODE BEGIN Init */
  /* The FSBL set the CPU to 600 MHz, but SystemCoreClockUpdate() is a stub in
   * the non-secure image. The HAL tick and the kernel's SysTick use this. */
  SystemCoreClock = HAL_RCC_GetCpuClockFreq();
  HAL_InitTick(TICK_INT_PRIORITY);
  /* USER CODE END Init */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_GPDMA1_Init();
  MX_MDF1_Init();
  MX_SAI1_Init();
  MX_I2C1_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */
  HAL_UARTEx_EnableFifoMode(&huart1);   /* at 2 Mbaud the RX FIFO is needed */
  Console_Init();
  /* keep the USART clocks running while the NPU runtime sleeps in WFE */
  __HAL_RCC_USART1_CLK_SLEEP_ENABLE();
  __HAL_RCC_PER_CLK_SLEEP_ENABLE();
  printf("App: alive in non-secure main(), starting micro T-Kernel 3.0\r\n");

  knl_start_mtkernel();   /* never returns */
  /* USER CODE END 2 */

  while (1)
  {
  }
}


